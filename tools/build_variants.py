"""Generate the internal test plugins from plugins/dikaia.

    python tools/build_variants.py          write internal/
    python tools/build_variants.py --check  exit 1 if internal/ differs from what would be written
"""

import json
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "plugins" / "dikaia"
INTERNAL = ROOT / "internal"

VARIANTS = [
    {"name": "dikaia-stage", "label": "stage", "url": "https://stage.dikaia.ai/mcp"},
    {"name": "dikaia-next", "label": "next", "url": "https://next.dikaia.ai/mcp"},
]


def dump(obj):
    return json.dumps(obj, indent=2, ensure_ascii=False) + "\n"


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def build_plugin(variant, dest):
    shutil.copytree(SOURCE, dest)

    manifest = json.loads((SOURCE / ".claude-plugin" / "plugin.json").read_text(encoding="utf-8"))
    manifest["name"] = variant["name"]
    manifest["displayName"] = f"{manifest.get('displayName', 'DIKAIA')} ({variant['label']})"
    manifest["description"] = f"[{variant['label'].upper()}] {manifest['description']}"
    write(dest / ".claude-plugin" / "plugin.json", dump(manifest))

    mcp = json.loads((SOURCE / ".mcp.json").read_text(encoding="utf-8"))
    (server,) = mcp["mcpServers"].values()
    server["url"] = variant["url"]
    write(dest / ".mcp.json", dump({"mcpServers": {variant["name"]: server}}))

    readme = (SOURCE / "README.md").read_text(encoding="utf-8")
    banner = (
        f"> Internal test build `{variant['name']}` against `{variant['url']}`. "
        f"Generated by `tools/build_variants.py`; edit `plugins/dikaia` instead. From a clone of this repository:\n\n"
        f"```\nclaude plugin marketplace add ./internal\nclaude plugin install {variant['name']}@dikaia-internal\n```\n\n"
    )
    write(dest / "README.md", banner + readme)


def build(out):
    public = json.loads((ROOT / ".claude-plugin" / "marketplace.json").read_text(encoding="utf-8"))
    (entry,) = public["plugins"]
    marketplace = {
        "name": "dikaia-internal",
        "description": "DIKAIA internal test builds (stage, next). Not for customers.",
        "owner": public["owner"],
        "plugins": [
            {
                "name": v["name"],
                "source": f"./plugins/{v['name']}",
                "description": f"[{v['label'].upper()}] {entry['description']}",
                "category": entry.get("category", "legal"),
            }
            for v in VARIANTS
        ],
    }
    write(out / ".claude-plugin" / "marketplace.json", dump(marketplace))
    for variant in VARIANTS:
        build_plugin(variant, out / "plugins" / variant["name"])


def tree(base):
    return {p.relative_to(base).as_posix(): p.read_bytes() for p in sorted(base.rglob("*")) if p.is_file()}


def main(argv):
    check = "--check" in argv
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "internal"
        build(out)
        if check:
            expected, actual = tree(out), tree(INTERNAL) if INTERNAL.exists() else {}
            drift = sorted(
                f"{'missing' if k not in actual else 'extra' if k not in expected else 'differs'}: internal/{k}"
                for k in expected.keys() | actual.keys()
                if expected.get(k) != actual.get(k)
            )
            if drift:
                print("internal/ is out of date; run python tools/build_variants.py", *drift, sep="\n  ")
                return 1
            print(f"internal/ is up to date ({len(expected)} files)")
            return 0
        if INTERNAL.exists():
            shutil.rmtree(INTERNAL)
        shutil.copytree(out, INTERNAL)
        print(f"wrote internal/ ({len(tree(INTERNAL))} files)")
        return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
